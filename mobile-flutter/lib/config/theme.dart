import 'package:flutter/material.dart';
import 'package:google_fonts/google_fonts.dart';

/// App Color Palette - Modern & Premium
class AppColors {
  // Primary Colors - Vibrant Purple/Indigo
  static const primary = Color(0xFF6366F1);
  static const primaryLight = Color(0xFF818CF8);
  static const primaryDark = Color(0xFF4F46E5);
  
  // Accent Colors
  static const accent = Color(0xFFF472B6);
  static const accentLight = Color(0xFFFBCFE8);
  
  // Background Colors
  static const background = Color(0xFF0F0F23);
  static const surface = Color(0xFF1A1A2E);
  static const surfaceLight = Color(0xFF25253A);
  static const card = Color(0xFF16162A);
  
  // Text Colors  
  static const textPrimary = Color(0xFFF8FAFC);
  static const textSecondary = Color(0xFF94A3B8);
  static const textMuted = Color(0xFF64748B);
  
  // Status Colors
  static const success = Color(0xFF10B981);
  static const warning = Color(0xFFF59E0B);
  static const error = Color(0xFFEF4444);
  static const info = Color(0xFF3B82F6);
  
  // Gradient Colors
  static const gradientStart = Color(0xFF6366F1);
  static const gradientEnd = Color(0xFFA855F7);
  
  // Glass Effect
  static const glassBorder = Color(0x1AFFFFFF);
  static const glassBackground = Color(0x0DFFFFFF);
